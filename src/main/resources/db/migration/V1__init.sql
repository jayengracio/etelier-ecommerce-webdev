-- Initial schema, matching the JPA entities in src/main/java/app.
-- Hibernate runs with ddl-auto=validate, so any change to an entity needs a new migration (V3__..., V4__...).

CREATE TABLE product (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type    VARCHAR(50),
    name    VARCHAR(255)     NOT NULL,
    stock   INTEGER          NOT NULL DEFAULT 0 CHECK (stock >= 0),
    details VARCHAR(1000),
    -- Product.price is a Double for now; switch to NUMERIC(10,2) + BigDecimal in a later migration
    price   DOUBLE PRECISION NOT NULL CHECK (price >= 0)
);

-- "user" is a reserved word in Postgres, hence "users" (see @Table on User)
CREATE TABLE users (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50)  NOT NULL UNIQUE,
    -- 255 leaves room for BCrypt/Argon2 hashes in phase 2
    password VARCHAR(255) NOT NULL,
    owner    BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Join tables for User.cart and User.orders (@ManyToMany List = bag).
-- No composite primary key: the same product can appear in a cart more than once.
CREATE TABLE users_cart (
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    cart_id INTEGER NOT NULL REFERENCES product (id) ON DELETE CASCADE
);
CREATE INDEX idx_users_cart_user ON users_cart (user_id);

CREATE TABLE users_orders (
    user_id   INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    orders_id INTEGER NOT NULL REFERENCES product (id) ON DELETE RESTRICT
);
CREATE INDEX idx_users_orders_user ON users_orders (user_id);
