CREATE TABLE product (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- DummyJSON's category ("smartphones", "kitchen-accessories").
    type    VARCHAR(50)   NOT NULL,
    name    VARCHAR(255)  NOT NULL,
    -- NULL: no brand (many groceries and furniture products have none).
    brand   VARCHAR(100),
    stock   INTEGER       NOT NULL DEFAULT 0 CHECK (stock >= 0),
    details VARCHAR(1000) NOT NULL,
    -- Money as exact decimals; DOUBLE PRECISION can't represent values like 0.10 exactly.
    price   NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    -- Stored and shown only: checkout still charges the full price.
    discount_percentage NUMERIC(5,2) NOT NULL DEFAULT 0
            CHECK (discount_percentage BETWEEN 0 AND 100),
    -- DummyJSON's star rating; it isn't the average of the reviews. NULL: not rated yet.
    rating  NUMERIC(3,2)  CHECK (rating BETWEEN 0 AND 5),
    -- Soft delete: order_items keeps referencing hidden products, so old orders still show them.
    active  BOOLEAN       NOT NULL DEFAULT TRUE,
    -- The main picture: a path in this app ('/images/x.png') or a full URL. NULL means none, and
    -- the pages show a placeholder. The check keeps out values that would give a broken image on
    -- some pages: '' or 'images/x.png' (a relative path breaks on /details/5). NULL passes a CHECK.
    image   VARCHAR(1000)
            CONSTRAINT product_image_check CHECK (image ~ '^(/|https?://)'),
    -- Every picture in order, for a gallery (the first is usually the same as image), and the tags.
    -- Arrays instead of extra tables: they're only ever read whole, together with the product.
    images  VARCHAR(1000)[] NOT NULL DEFAULT '{}',
    tags    VARCHAR(50)[]   NOT NULL DEFAULT '{}'
);

-- "user" is a reserved word in Postgres, hence "users".
CREATE TABLE users (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,  -- bcrypt hash
    role     VARCHAR(20)  NOT NULL DEFAULT 'USER'
             CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN'))
);

-- "order" is a reserved word too, hence "orders".
CREATE TABLE orders (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    -- PENDING -> PAID (webhook) -> SHIPPED, or PENDING -> CANCELLED (expired / out of stock),
    -- or PAID -> REFUNDED (admin refund, stock goes back).
    status     VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
               CONSTRAINT orders_status_check
               CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'CANCELLED', 'REFUNDED')),
    total      NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- The Checkout Session that pays for this order. NULL briefly for a new order (it needs
    -- its id before the session exists). UNIQUE allows many NULLs and indexes webhook lookups.
    stripe_session_id        VARCHAR(255) CONSTRAINT orders_stripe_session_id_unique UNIQUE,
    -- The PaymentIntent (pi_...) that charged it; refunds and the Dashboard link use it.
    stripe_payment_intent_id VARCHAR(255)
);
CREATE INDEX idx_orders_user ON orders (user_id);

CREATE TABLE order_items (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   INTEGER       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id INTEGER       NOT NULL REFERENCES product (id) ON DELETE RESTRICT,
    quantity   INTEGER       NOT NULL CHECK (quantity > 0),
    -- The price at the time of purchase, so later price changes don't rewrite old orders.
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE cart_items (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    CONSTRAINT cart_items_user_product_unique UNIQUE (user_id, product_id)
);

-- Reviews come from DummyJSON's sample reviewers, who aren't accounts here, hence a name and no
-- user_id. (DummyJSON's made-up reviewer emails aren't stored.)
CREATE TABLE reviews (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    INTEGER       NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    rating        INTEGER       NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment       VARCHAR(1000) NOT NULL,
    reviewer_name VARCHAR(100)  NOT NULL,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_reviews_product ON reviews (product_id);
