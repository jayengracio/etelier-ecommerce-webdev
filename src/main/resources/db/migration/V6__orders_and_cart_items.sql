-- Phase 3: real cart and order model. The old join tables stay until V7.

-- V5's type change rewrote the price CHECK with casts to double precision; restore a plain one.
ALTER TABLE product DROP CONSTRAINT product_price_check;
ALTER TABLE product ADD CONSTRAINT product_price_check CHECK (price >= 0);

-- "order" is a reserved word, hence "orders" (map with @Table(name = "orders")).
CREATE TABLE orders (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    status     VARCHAR(20)   NOT NULL DEFAULT 'PENDING'
               CONSTRAINT orders_status_check CHECK (status IN ('PENDING', 'PAID', 'SHIPPED')),
    total      NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_orders_user ON orders (user_id);

CREATE TABLE order_items (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   INTEGER       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id INTEGER       NOT NULL REFERENCES product (id) ON DELETE RESTRICT,
    quantity   INTEGER       NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0)
);
CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE cart_items (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    quantity   INTEGER NOT NULL CHECK (quantity > 0),
    CONSTRAINT cart_items_user_product_unique UNIQUE (user_id, product_id)
);

-- Carts: duplicate rows become one row with a quantity.
INSERT INTO cart_items (user_id, product_id, quantity)
SELECT user_id, cart_id, count(*)
FROM users_cart
GROUP BY user_id, cart_id;

-- Carts no longer reserve stock (stock is taken at purchase), so give back what old carts reserved.
UPDATE product p
SET    stock = p.stock + c.cnt
FROM  (SELECT cart_id, count(*) AS cnt FROM users_cart GROUP BY cart_id) c
WHERE  p.id = c.cart_id;

-- Old purchases: one order per user. The price paid was never stored, so use today's price.
INSERT INTO orders (user_id, status, total)
SELECT uo.user_id, 'PAID', sum(p.price)
FROM users_orders uo
JOIN product p ON p.id = uo.orders_id
GROUP BY uo.user_id;

-- orders only holds the rows just inserted (one per user), so joining on user_id is unambiguous.
INSERT INTO order_items (order_id, product_id, quantity, unit_price)
SELECT o.id, uo.orders_id, count(*), p.price
FROM users_orders uo
JOIN orders  o ON o.user_id = uo.user_id
JOIN product p ON p.id = uo.orders_id
GROUP BY o.id, uo.orders_id, p.price;
