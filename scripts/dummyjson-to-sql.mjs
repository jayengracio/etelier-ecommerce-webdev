// Writes the product seed migration from DummyJSON's product list (https://dummyjson.com/docs/products).
//
//   node scripts/dummyjson-to-sql.mjs
//
// The SQL file is committed, so builds and tests never need DummyJSON. Run this again only for a
// fresh database (docker compose down -v): Flyway refuses to start when an applied migration changes.

import { writeFile } from "node:fs/promises";

const SOURCE = "https://dummyjson.com/products?limit=0"; // limit=0 means "all of them"
const OUTPUT = new URL("../src/main/resources/db/migration/V3__dummyjson_products.sql", import.meta.url);

// '' is how SQL writes a ' inside a string ("Women's" -> 'Women''s').
const text = (value) => (value == null ? "NULL" : `'${String(value).replaceAll("'", "''")}'`);
// Money and ratings as exact decimals: toFixed avoids float output like 9.990000000000002.
const decimal = (value) => value.toFixed(2);
const array = (values) => `ARRAY[${values.map(text).join(", ")}]`;

const response = await fetch(SOURCE);
if (!response.ok) {
    throw new Error(`${SOURCE} answered ${response.status}`);
}
const { products } = await response.json();

// DummyJSON has two "Rolex Cellini Moonphase". The second one is hidden, which also gives the
// admin's product list a hidden product to show.
const seenNames = new Set();
const productRows = products.map((p) => {
    const active = !seenNames.has(p.title);
    seenNames.add(p.title);
    return `    (${[
        p.id,
        text(p.category),
        text(p.title),
        text(p.brand),
        p.stock,
        text(p.description),
        decimal(p.price),
        decimal(p.discountPercentage),
        decimal(p.rating),
        active ? "TRUE" : "FALSE",
        text(p.images[0]),
        array(p.images),
        array(p.tags),
    ].join(", ")})`;
});

const reviewRows = products.flatMap((p) =>
    p.reviews.map(
        (r) => `    (${[p.id, r.rating, text(r.comment), text(r.reviewerName), text(r.date)].join(", ")})`,
    ),
);

const sql = `-- Generated by scripts/dummyjson-to-sql.mjs from ${SOURCE}
-- on ${new Date().toISOString().slice(0, 10)}: ${productRows.length} products, ${reviewRows.length} reviews.
-- Don't edit it by hand: change the script and run it again (only for a fresh database).
-- Prices are DummyJSON's dollar amounts, shown as euros. Pictures stay on DummyJSON's CDN.

-- DummyJSON's own ids, so /details/1 is https://dummyjson.com/products/1.
INSERT INTO product (id, type, name, brand, stock, details, price, discount_percentage, rating,
                     active, image, images, tags) VALUES
${productRows.join(",\n")};

-- Inserting ids by hand doesn't move the identity counter. Without this, the next product an
-- admin adds would get id 1 and fail with a duplicate key.
SELECT setval(pg_get_serial_sequence('product', 'id'), (SELECT max(id) FROM product));

INSERT INTO reviews (product_id, rating, comment, reviewer_name, created_at) VALUES
${reviewRows.join(",\n")};
`;

await writeFile(OUTPUT, sql);
console.log(`Wrote ${productRows.length} products and ${reviewRows.length} reviews to ${OUTPUT.pathname}`);
